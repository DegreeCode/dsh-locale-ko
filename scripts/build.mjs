// Generate client.js from dictionaries/*.json.
// Usage: node scripts/build.mjs          (write client.js)
//        node scripts/build.mjs --check  (fail when client.js is stale or a dictionary is invalid)
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const pkg = JSON.parse(readFileSync(`${root}package.json`, 'utf8'))
const LANGUAGE = { id: 'ko', label: '한국어', fallback: 'en' }

const problems = []
const dictionaries = {}
for (const file of readdirSync(`${root}dictionaries`).filter(name => name.endsWith('.json')).sort()) {
  const namespace = file.slice(0, -'.json'.length)
  const dict = JSON.parse(readFileSync(`${root}dictionaries/${file}`, 'utf8'))
  for (const [key, text] of Object.entries(dict)) {
    if (typeof text !== 'string') problems.push(`${file}: ${key} is not a string`)
    else if (/[​﻿]/u.test(text)) problems.push(`${file}: ${key} contains an invisible character`)
  }
  dictionaries[namespace] = dict
}

const source = `// Generated by scripts/build.mjs from dictionaries/*.json — do not edit by hand.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory() {
    const LANGUAGE = ${JSON.stringify(LANGUAGE)};
    const DICTIONARIES = ${JSON.stringify(dictionaries)};
    const noop = () => {};
    return {
      inject: ['locale'],
      apply(ctx) {
        // A Harness that already ships Korean keeps its own definition and dictionaries.
        ctx.effect(() => {
          if (ctx.locale.getLocale().locales.some(definition => definition.id === LANGUAGE.id)) return noop;
          return ctx.locale.addLanguage(LANGUAGE);
        }, ${JSON.stringify(`${pkg.name}: language`)});
        for (const [namespace, dict] of Object.entries(DICTIONARIES)) {
          ctx.effect(() => {
            try {
              return ctx.locale.register(namespace, LANGUAGE.id, dict);
            } catch (error) {
              console.warn(${JSON.stringify(`[${pkg.name}]`)}, 'skipped namespace', namespace, error);
              return noop;
            }
          }, ${JSON.stringify(`${pkg.name}: `)} + namespace);
        }
      },
    };
  },
});
`

const target = `${root}client.js`
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== source) problems.push('client.js is stale; run npm run build')
} else {
  writeFileSync(target, source)
}
const keys = Object.values(dictionaries).reduce((n, dict) => n + Object.keys(dict).length, 0)
if (problems.length > 0) {
  for (const problem of problems) console.error(problem)
  process.exit(1)
}
console.log(`${Object.keys(dictionaries).length} namespaces, ${keys} keys${process.argv.includes('--check') ? ' — client.js is current' : ' → client.js'}`)
